import 'dart:convert';
import 'dart:io';

// Public OAuth identifiers only. Never reads or writes a client secret.
void main(List<String> args) {
  final input = File(args.isEmpty ? 'env/dev.json' : args.single);
  final values = jsonDecode(input.readAsStringSync()) as Map<String, dynamic>;
  final ios = (values['GOOGLE_IOS_CLIENT_ID'] as String? ?? '').trim();
  final reversed = (values['GOOGLE_IOS_REVERSED_CLIENT_ID'] as String? ?? '').trim();
  final configured = ios.isNotEmpty && !ios.contains('your-');
  if (configured && !RegExp(r'^[a-zA-Z0-9-]+\.apps\.googleusercontent\.com$').hasMatch(ios)) {
    throw FormatException('GOOGLE_IOS_CLIENT_ID must be an iOS OAuth client ID.');
  }
  final expected = ios.split('.').reversed.join('.');
  if (configured && reversed != expected) {
    throw FormatException('GOOGLE_IOS_REVERSED_CLIENT_ID must be the reversed iOS client ID: $expected');
  }
  final scheme = configured ? reversed : 'com.ezyreminder.google-unconfigured';
  File('ios/Flutter/AuthConfig.xcconfig').writeAsStringSync(
    '// Generated by tool/configure_ios_auth.dart; public URL scheme only.\nGOOGLE_REVERSED_CLIENT_ID = $scheme\n',
  );
  stdout.writeln(configured
      ? 'Google callback URL scheme configured. Rebuild the app to apply it.'
      : 'Google iOS client ID is not configured. Provider buttons remain visible with setup guidance.');
}
