import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const config = JSON.parse(readFileSync(new URL('design/home-templates.json', root), 'utf8'));
// JSON's nested literals are valid Dart constant map/list literals here.
const dart = `// GENERATED by scripts/gen-home-templates.mjs from design/home-templates.json.\nconst homeSectionData = <String, dynamic>${JSON.stringify(config.sections, null, 2)};\nconst homeTemplateData = <String, dynamic>${JSON.stringify(config.templates, null, 2)};\n`;
const path = fileURLToPath(new URL('mobile/lib/features/home/home_templates.g.dart', root));
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== dart) throw Error('Home templates are out of date. Run node scripts/gen-home-templates.mjs');
  const prototype = readFileSync(new URL('design/prototype.html',root),'utf8');
  if(!prototype.includes(`const HOME_CONFIG = ${JSON.stringify(config)};`)) throw Error('Prototype Home templates are out of date');
} else {
  writeFileSync(path, dart);
  const prototypePath=new URL('design/prototype.html',root);
  const prototype=readFileSync(prototypePath,'utf8').replace(/\/\* BEGIN HOME TASK TEMPLATES \*\/[\s\S]*?\/\* END HOME TASK TEMPLATES \*\//, `/* BEGIN HOME TASK TEMPLATES */\nconst HOME_CONFIG = ${JSON.stringify(config)};\n/* END HOME TASK TEMPLATES */`);
  writeFileSync(prototypePath,prototype);
}
